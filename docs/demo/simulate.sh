#!/usr/bin/env bash
# Simulate real use: three nodes on a local file bus run every command,
# with each step's output, exit code and wall time captured. Writes the
# measured sections of docs/USAGE-REPORT.md. Run from the repo root:
#   bash docs/demo/simulate.sh
set -u
cd "$(dirname "$0")/../.."
export NO_COLOR=1 TG_DEMO=/tmp/telegraph-sim
. docs/demo/env.sh
REPORT=docs/USAGE-REPORT.md
STEPS=$(mktemp)
pass=0 fail=0 total_ms=0

ms() { date +%s%N; }

# step EXPECT NODE ARGS... — EXPECT is ok or err (a refusal we want).
step() {
	local expect=$1 node=$2; shift 2
	local t0 t1 out code took mark
	t0=$(ms); out=$("$node" "$@" 2>&1); code=$?; t1=$(ms)
	took=$(( (t1 - t0) / 1000000 )); total_ms=$((total_ms + took))
	if { [ "$expect" = ok ] && [ $code -eq 0 ]; } || { [ "$expect" = err ] && [ $code -ne 0 ]; }; then
		mark=✓; pass=$((pass + 1))
	else
		mark=✗; fail=$((fail + 1))
	fi
	LAST_OUT=$out
	{
		printf '### %s `%s %s`\n\n' "$mark" "$node" "$*"
		printf -- '- exit %d (expected %s), %d ms\n\n' "$code" "$expect" "$took"
		printf '```\n%s\n```\n\n' "$out"
	} >>"$STEPS"
}

entries() { grep -c '"ha"' "$TG_DEMO/$1/data.json"; }

step ok alice version
step ok alice register --handle alice@nym --did did:key:alice
step ok bob register --handle bob@nym --did did:key:bob
step ok carol register --handle carol@nym --did did:key:carol
step err carol register --handle x@nym
for n in alice bob carol alice bob carol; do step ok $n sync --secs 0; done
SYNC1="alice $(entries alice) · bob $(entries bob) · carol $(entries carol)"
step ok alice resolve bob@nym
step ok carol audit
for n in alice bob carol; do
	step ok $n checkpoint
	case $LAST_OUT in *issued*) LEADER=$n ;; esac
done
step ok "${LEADER:-alice}" checkpoint
for n in alice bob carol alice bob carol; do step ok $n sync --secs 0; done
step ok alice audit
step ok bob audit
step ok carol audit
CP_LINE=$(carol audit | grep -E 'committee')
step ok carol verify alice@nym
step ok alice pin
PIN=$(alice pin | awk '/^✓ pin/{print $3}')
step ok alice net
step ok alice peers
step ok alice card --handle alice@nym
LINE=$(alice card --handle alice@nym | head -1)
step err carol scan "$LINE"
step ok alice attest --line "$LINE"
for n in alice carol; do step ok $n sync --secs 0; done
step ok carol scan "$LINE"
step ok alice swap offer --gives alice@nym --wants bob@nym --hours 1
SID=$(printf '%s\n' "$LAST_OUT" | awk '/swap id/{print $3}')
step err bob swap claim --sid "$SID"
for n in alice bob; do step ok $n sync --secs 0; done
step ok bob swap accept --sid "$SID"
for n in bob alice; do step ok $n sync --secs 0; done
step ok alice swap claim --sid "$SID"
for n in alice bob; do step ok $n sync --secs 0; done
step ok bob swap claim --sid "$SID"
step err alice swap reclaim --sid "$SID"
for n in bob alice bob carol alice; do step ok $n sync --secs 0; done
step ok carol swap status --sid "$SID"
step ok carol resolve alice@nym
step ok carol resolve bob@nym
step ok carol audit
FINAL="alice $(entries alice) · bob $(entries bob) · carol $(entries carol)"
OWN_A=$(carol resolve alice@nym | awk '$1=="owner"{print $2}')
OWN_B=$(carol resolve bob@nym | awk '$1=="owner"{print $2}')
KEY_A=$(alice init | awk '$1=="key"{print $2}' | tr -d '…')
KEY_B=$(bob init | awk '$1=="key"{print $2}' | tr -d '…')
# A fourth node joins with only the pin, while alice serves its dump.
dave() { TELEGRAPH_HOME="$TG_DEMO/dave" telegraph "$@"; }
step err dave resolve alice@nym
step ok dave init
alice sync --secs 3 >/dev/null 2>&1 &
step ok dave sync --secs 2 --pin "$PIN"
FRESH=$LAST_OUT
wait
step ok dave verify carol@nym
step err dave scan "$LINE" # card predates the swap, so it must read STALE
# A fifth node starts a separate, brand-new network: no pin exists yet.
erin() { TELEGRAPH_HOME="$TG_DEMO/erin" TELEGRAPH_BUS="$TG_DEMO/bus2.jsonl" telegraph "$@"; }
step ok erin init
step err erin sync --secs 0 # empty store and no pin: refuses to guess
step ok erin sync --secs 0 --genesis
step err erin sync --secs 0 --genesis --pin "$PIN" # genesis and a pin conflict

{
	cat <<HDR
# Telegraph usage report

Generated by \`bash docs/demo/simulate.sh\` on $(date -u +%Y-%m-%dT%H:%M:%SZ) (UTC),
$(go version | cut -d' ' -f3-), $(uname -sm). Every number below was measured in that run.
Three nodes (alice, bob, carol) ran as separate processes with separate
\`TELEGRAPH_HOME\` directories, gossiping over a local file bus
(\`TELEGRAPH_BUS\`) instead of Telegram.

## Summary

| | |
|---|---|
| Steps run | $((pass + fail)) |
| Result | ✓ $pass as expected · ✗ $fail unexpected |
| Total command time | ${total_ms} ms |
| Nodes | 3, plus 1 late joiner (dave) and 1 genesis node on its own bus (erin) |
| Entries per node after first sync | $SYNC1 |
| Entries per node at the end | $FINAL |
| Checkpoint leader | ${LEADER:-none} |
| Checkpoint audit | \`$(echo "$CP_LINE" | tr -s ' ' | sed 's/^ //')\` |
| Swap | alice@nym now owned by \`$OWN_A\` (bob's key \`$KEY_B\`), bob@nym by \`$OWN_B\` (alice's key \`$KEY_A\`) |
| Fresh node bootstrapping with the pin | \`$(echo "$FRESH" | tail -1)\` |

"Expected" includes refusals the CLI should make: registering without
\`--did\`, scanning a card before it is attested, claiming before the
counterparty has locked, reclaiming before expiry, using a node before
\`init\`, scanning a card issued before its handle was swapped (STALE),
syncing an empty store with neither \`--pin\` nor \`--genesis\`, and
combining \`--genesis\` with a pin.

## Steps

HDR
	cat "$STEPS"
	cat docs/demo/findings.md
} >"$REPORT"
rm -f "$STEPS"
echo "wrote $REPORT: $pass ok, $fail unexpected, ${total_ms} ms"
[ "$fail" -eq 0 ]
